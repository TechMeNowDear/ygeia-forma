/// SHA-256 (FIPS 180-4) σε καθαρή Dart, χωρίς βιβλιοθήκη: το χρειάζεται μόνο το PKCE της σύνδεσης Oura
/// (code_challenge = BASE64URL(SHA256(code_verifier))). Ελέγχεται με τα παραδείγματα του RFC 7636 και της Oura.
