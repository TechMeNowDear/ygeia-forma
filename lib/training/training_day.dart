// Η μέρα της προπόνησης (απόφαση χρήστη 21/11, Α13).
//
// Η «σημερινή» προπόνηση άλλαζε στα μεσάνυχτα, ενώ το φαγητό κρατά τη «χθεσινή μέρα» ως τις 04:00
// (food_store.dart). Όποιος γυμνάζεται στις 00:30 της Παρασκευής προς Σάββατο έβλεπε ήδη την προπόνηση του
// Σαββάτου, και η προπόνηση που έκανε μετρούσε στο Σάββατο. Τώρα και η μέρα της προπόνησης αλλάζει στις 04:00.
// Το ίδιο κάνει το ρολόι (Protocol.kt, trainingDate) και το widget «Προπόνηση σήμερα» (QuickWidgetRules.kt).
library;

/// Η ώρα που αλλάζει η μέρα της προπόνησης (όπως του φαγητού).
const trainingDayStartHour = 4;

/// Η μέρα της προπόνησης (μεσάνυχτα) της στιγμής [t]: 00:00–03:59 ανήκει στην προηγούμενη μέρα.
///
/// Μια τιμή ακριβώς στα μεσάνυχτα (00:00:00.000) είναι ΗΜΕΡΟΜΗΝΙΑ, όχι στιγμή, και μένει ίδια: έτσι η συνάρτηση
/// δίνει το ίδιο όταν ξανατρέξει πάνω στο αποτέλεσμά της, και όσες συναρτήσεις παίρνουν «μέρα» (π.χ. η εβδομάδα
/// της οθόνης «Άσκηση») δουλεύουν όπως πριν. Πραγματική στιγμή ακριβώς στα μεσάνυχτα, ως το χιλιοστό του
/// δευτερολέπτου, δεν βγαίνει από ρολόι στην πράξη.
DateTime trainingDay(DateTime t) {
  final midnight = t.hour == 0 && t.minute == 0 && t.second == 0 && t.millisecond == 0 && t.microsecond == 0;
  return t.hour < trainingDayStartHour && !midnight ? DateTime(t.year, t.month, t.day - 1) : DateTime(t.year, t.month, t.day);
}

/// Οι στιγμές [a] και [b] είναι στην ίδια μέρα προπόνησης ([trainingDay]).
bool sameTrainingDay(DateTime a, DateTime b) {
  final x = trainingDay(a), y = trainingDay(b);
  return x.year == y.year && x.month == y.month && x.day == y.day;
}
