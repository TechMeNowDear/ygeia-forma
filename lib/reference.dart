/// Λίπος σώματος (Gallagher κ.ά. 2000, πίνακας 4): τα όρια που αντιστοιχούν στον φυσιολογικό δείκτη μάζας σώματος,
/// ανά φύλο και ηλικία 20–79. Για άλλες ηλικίες ή χωρίς φύλο: κανένα εύρος.
/// Round 1 (S4-6): τα όρια βγήκαν από μέτρηση εργαστηρίου (μοντέλο 4 διαμερισμάτων και DXA)· οι ζυγαριές InBody δείχνουν
/// συνήθως ΛΙΓΟΤΕΡΟ λίπος από το DXA (McLester κ.ά., J Clin Densitom 2020: συστηματική απόκλιση σε κάθε σύγκριση· το μέγεθος
/// δεν είναι στην περίληψη). Γι' αυτό το κείμενο το λέει, και τιμή έως [fatNearBelow] μονάδα κάτω από ένα όριο λέγεται
/// «κοντά στο … όριο» (π.χ. 21,4% με όριο 22: όχι «μέσα στο εύρος»). Η 1 μονάδα = το τυπικό σφάλμα μέτρησης της ίδιας
/// μελέτης (0,77–0,99).
const fatNearBelow = 1.0;

RefRange? fatRange(Profile p, DateTime today) {
  final age = p.ageOn(today);
  if (age == null || age < 20 || age > 79 || p.sex == null) return null;
  final band = age < 40 ? 0 : (age < 60 ? 1 : 2);
  final (lo, hi) = p.male ? const [(8.0, 20.0), (11.0, 22.0), (13.0, 25.0)][band] : const [(21.0, 33.0), (23.0, 34.0), (24.0, 36.0)][band];
  final who = p.male ? 'άνδρες' : 'γυναίκες';
  final ages = const ['20–39', '40–59', '60–79'][band];
  return RefRange(
    low: lo,
    high: hi,
    nearBelow: fatNearBelow,
    text: '${lo.round()}–${hi.round() - 1},9% για $who $ages ετών, σε μέτρηση εργαστηρίου (DXA)· η ζυγαριά δείχνει συνήθως '
        'λιγότερο',
    cite: 'Gallagher κ.ά., American Journal of Clinical Nutrition 2000. Τα όρια βγαίνουν από τον δείκτη μάζας '
        'σώματος, όχι από μελέτες κινδύνου',
  );
}

/// Δείκτης μάζας σώματος: φυσιολογικός 18,5–24,9 (ΠΟΥ), για ενήλικες.
const bmiRange = RefRange(low: 18.5, high: 25, text: '18,5–24,9 (φυσιολογικό)', cite: 'Παγκόσμιος Οργανισμός Υγείας');

/// Το βάρος που αντιστοιχεί στον φυσιολογικό δείκτη για το ύψος [heightCm]: (από, ως) σε kg.
(double, double)? healthyWeight(double? heightCm) {
  if (heightCm == null) return null;
  final m = heightCm / 100;
  // Ίδιο όριο με τον δείκτη (κάτω από 25): πριν 24,9 → ένα βάρος έδειχνε δείκτη «24,9» και «πάνω από το εύρος» (έλεγχος 8/11, MED-12).
  return (18.5 * m * m, 25 * m * m);
}

/// Το ύψος που χρησιμοποίησε η ζυγαριά, από το βάρος και τον δείκτη της (cm).
double? inBodyHeight(double? weight, double? bmi) =>
    weight == null || bmi == null || bmi <= 0 ? null : math.sqrt(weight / bmi) * 100;

/// Δείκτης μάζας σώματος από βάρος και ύψος.
double? bmiOf(double? weight, double? heightCm) =>
    weight == null || heightCm == null ? null : weight / math.pow(heightCm / 100, 2);

/// Round 7 (A4-2): ο δείκτης όπως γράφεται: ΚΟΜΜΕΝΟΣ στο 0,1, ποτέ στρογγυλεμένος προς τα πάνω, ώστε ο αριθμός να συμφωνεί
/// με την κρίση του εύρους ([bmiRange]: κάτω από 25). Πριν 24,97 (180 cm, 80,9 kg) γραφόταν «25,0» δίπλα στο «μέσα στο
/// εύρος» «18,5–24,9». Ίδιος κανόνας με το οξυγόνο (`lowestText`, `spo2AvgText`).
String bmiText(double bmi) => dec(bmiShown(bmi));

/// Round 8 (R8-A4-1): ο δείκτης όπως φαίνεται ([bmiText]), ως αριθμός: η κρίση του εύρους γίνεται ΜΕ ΑΥΤΟΝ
/// (`bmiRange.placeText(bmiShown(bmi))`), ώστε αριθμός και κρίση να μη διαφωνούν ποτέ. Πριν, 160 cm και 64,0 kg: 64 /
/// 1,6² βγαίνει 24,999999999999996 σε double (1,6 × 1,6 = 2,5600000000000005)· γραφόταν «25,0» (με το +1e-9) αλλά
/// κρινόταν «μέσα στο εύρος», ενώ το βάρος (64,0 ≥ 25 × 1,6²) «πάνω από το εύρος». Σάρωση 140,0–210,0 cm × 30,0–200,0 kg
/// ανά 0,1 (και με βάρη float32 της Samsung): κρίση δείκτη = κρίση βάρους παντού (/home/claude/scratch/f5r8/bmi.py).
double bmiShown(double bmi) => (bmi * 10 + 1e-9).floorToDouble() / 10;

/// Round 7 (A4-2): το βάρος του φυσιολογικού δείκτη σε λέξεις, «60,0–80,9» για 180 cm: τα άκρα είναι οι τιμές της ζυγαριάς
/// (ανά 0,1 kg) που η εφαρμογή κρίνει «μέσα στο εύρος» ([RefRange.place]: από [lo], κάτω από [hi]). Πριν «59,9–81,0»: τα
/// 81,0 kg (δείκτης 25,0) έβγαιναν «πάνω από το εύρος» με το 81,0 μέσα στο κείμενο, και τα 59,9 (18,49) «κάτω».
String healthyWeightText(double lo, double hi) {
  final from = (lo * 10 - 1e-9).ceil();
  final to = (hi * 10 - 1e-9).ceil() - 1;
  return '${dec(from / 10)}–${dec(to / 10)}';
}

/// Βήματα (Paluch κ.ά. 2022): ο κίνδυνος θανάτου μειώνεται ως περίπου 8.000–10.000 βήματα (κάτω των 60) ή
/// 6.000–8.000 (60 και πάνω) και μετά σταθεροποιείται. Δεν είναι «ανώτατο»· είναι το σημείο που σταματά το όφελος.
