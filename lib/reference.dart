/// Ένα δημοσιευμένο εύρος: [low] ≤ τιμή < [high] (όποιο λείπει, δεν υπάρχει όριο από εκείνη την πλευρά).
class RefRange {
  const RefRange({this.low, this.high, required this.text, required this.cite});
  final double? low;
  final double? high;

  /// Το εύρος σε λέξεις, π.χ. «11–22% για άνδρες 40–59 ετών».
  final String text;

  /// Η πηγή, σύντομα.
  final String cite;

  /// −1 κάτω, 0 μέσα, +1 πάνω.
  int place(double v) {
    if (low != null && v < low!) return -1;
    if (high != null && v >= high!) return 1;
    return 0;
  }

  String placeText(double v) => switch (place(v)) {
        -1 => 'κάτω από το εύρος',
        1 => 'πάνω από το εύρος',
        _ => 'μέσα στο εύρος',
      };
}

/// Ύπνος: τουλάχιστον 7 ώρες για ενήλικες 18–60 ετών (σύσταση AASM/SRS). Μετρά ο πραγματικός ύπνος.
RefRange? sleepRange(Profile p, DateTime today) {
  final age = p.ageOn(today);
  if (age != null && (age < 18 || age > 60)) return null;
  return const RefRange(
    low: 7 * 60,
    text: 'τουλάχιστον 7 ώρες για ενήλικες',
    cite: 'AASM και Sleep Research Society (Watson κ.ά., Sleep 2015), ενήλικες 18–60 ετών',
  );
}

/// Αναπνοές στον ύπνο: 9 στους 10 υγιείς ενήλικες 11,8–19,2 το λεπτό (Natarajan κ.ά., npj Digit Med 2021, Fitbit).
/// Όχι πια το NEWS2 (12–20): είναι κλίμακα για άρρωστους ασθενείς σε ξύπνιους, όχι εύρος για υγιείς που κοιμούνται
/// (έλεγχος #2).
const breathRange = RefRange(
  low: 11.8,
  high: 19.25,
  text: 'περίπου 12–19 το λεπτό στον ύπνο (9 στους 10 υγιείς ενήλικες)',
  cite: 'Natarajan κ.ά., npj Digital Medicine 2021 (ρολόι Fitbit)',
);

/// Λίπος σώματος (Gallagher κ.ά. 2000, πίνακας 4): τα όρια που αντιστοιχούν στον φυσιολογικό δείκτη μάζας σώματος,
/// ανά φύλο και ηλικία 20–79. Για άλλες ηλικίες ή χωρίς φύλο: κανένα εύρος.
RefRange? fatRange(Profile p, DateTime today) {
  final age = p.ageOn(today);
  if (age == null || age < 20 || age > 79 || p.sex == null) return null;
  final band = age < 40 ? 0 : (age < 60 ? 1 : 2);
  final (lo, hi) = p.male ? const [(8.0, 20.0), (11.0, 22.0), (13.0, 25.0)][band] : const [(21.0, 33.0), (23.0, 34.0), (24.0, 36.0)][band];
  final who = p.male ? 'άνδρες' : 'γυναίκες';
  final ages = const ['20–39', '40–59', '60–79'][band];
  return RefRange(
    low: lo,
    high: hi,
    text: '${lo.round()}–${hi.round() - 1},9% για $who $ages ετών',
    cite: 'Gallagher κ.ά., American Journal of Clinical Nutrition 2000. Τα όρια βγαίνουν από τον δείκτη μάζας '
        'σώματος, όχι από μελέτες κινδύνου',
  );
}

/// Δείκτης μάζας σώματος: φυσιολογικός 18,5–24,9 (ΠΟΥ), για ενήλικες.
const bmiRange = RefRange(low: 18.5, high: 25, text: '18,5–24,9 (φυσιολογικό)', cite: 'Παγκόσμιος Οργανισμός Υγείας');

/// Το βάρος που αντιστοιχεί στον φυσιολογικό δείκτη για το ύψος [heightCm]: (από, ως) σε kg.
(double, double)? healthyWeight(double? heightCm) {
  if (heightCm == null) return null;
  final m = heightCm / 100;
  // Ίδιο όριο με τον δείκτη (κάτω από 25): πριν 24,9 → ένα βάρος έδειχνε δείκτη «24,9» και «πάνω από το εύρος» (έλεγχος 8/11, MED-12).
  return (18.5 * m * m, 25 * m * m);
}

/// Το ύψος που χρησιμοποίησε η ζυγαριά, από το βάρος και τον δείκτη της (cm).
double? inBodyHeight(double? weight, double? bmi) =>
    weight == null || bmi == null || bmi <= 0 ? null : math.sqrt(weight / bmi) * 100;

/// Δείκτης μάζας σώματος από βάρος και ύψος.
double? bmiOf(double? weight, double? heightCm) =>
    weight == null || heightCm == null ? null : weight / math.pow(heightCm / 100, 2);

/// Βήματα (Paluch κ.ά. 2022): ο κίνδυνος θανάτου μειώνεται ως περίπου 8.000–10.000 βήματα (κάτω των 60) ή
/// 6.000–8.000 (60 και πάνω) και μετά σταθεροποιείται. Δεν είναι «ανώτατο»· είναι το σημείο που σταματά το όφελος.
RefRange? stepsRange(Profile p, DateTime today) {
  final age = p.ageOn(today);
  final older = age != null && age >= 60;
  return RefRange(
    low: older ? 6000 : 8000,
    text: older
        ? 'το όφελος σταθεροποιείται γύρω στα 6.000–8.000 (60 ετών και πάνω)'
        : 'το όφελος σταθεροποιείται γύρω στα 8.000–10.000 (κάτω των 60)',
    cite: 'Paluch κ.ά., Lancet Public Health 2022 (15 μελέτες, 47.471 ενήλικες)',
  );
}

/// Χαμηλότερο οξυγόνο της νύχτας σε υγιείς (εργαστήριο ύπνου): 90,4% ± 3,1. Μόνο ως πλαίσιο, όχι όριο συναγερμού
/// (οι σημειώσεις έχουν τους δικούς τους κανόνες, oxygen_note.dart).
const oxygenLowContext = 'Σε 350 υγιείς σε εργαστήριο ύπνου, η χαμηλότερη τιμή της νύχτας ήταν κατά μέσο όρο 90,4% '
    '(± 3,1). Στους άνω των 60, η μεσαία τιμή στον ύπνο ήταν 95,1% (± 2,0)· στους νεότερους λίγο πιο ψηλά.';
