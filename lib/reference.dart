/// Ένα δημοσιευμένο εύρος: [low] ≤ τιμή < [high] (όποιο λείπει, δεν υπάρχει όριο από εκείνη την πλευρά).
class RefRange {
  const RefRange({this.low, this.high, required this.text, required this.cite, this.nearBelow = 0});
  final double? low;
  final double? high;

  /// Round 1 (S4-5, S4-6): η συσκευή μετρά συνήθως ΛΙΓΟΤΕΡΟ από τη μέθοδο πάνω στην οποία βγήκε το εύρος (ύπνος: ώρες
  /// που δήλωναν οι ίδιοι οι άνθρωποι· λίπος: μέτρηση DXA). Τιμή έως τόσο ΚΑΤΩ από ένα όριο λέγεται «κοντά στο … όριο»
  /// ([placeText]), όχι «κάτω από το εύρος» ή «μέσα στο εύρος». 0 = κανένα περιθώριο. Το [place] μένει αυστηρό.
  final double nearBelow;

  /// Το εύρος σε λέξεις, π.χ. «11–22% για άνδρες 40–59 ετών».
  final String text;

  /// Η πηγή, σύντομα.
  final String cite;

  /// −1 κάτω, 0 μέσα, +1 πάνω.
  int place(double v) {
    if (low != null && v < low!) return -1;
    if (high != null && v >= high!) return 1;
    return 0;
  }

  String placeText(double v) {
    if (nearBelow > 0) {
      if (low != null && v < low! && v >= low! - nearBelow) return 'κοντά στο κάτω όριο';
      if (high != null && v < high! && v >= high! - nearBelow) return 'κοντά στο πάνω όριο';
    }
    return switch (place(v)) {
      -1 => 'κάτω από το εύρος',
      1 => 'πάνω από το εύρος',
      _ => 'μέσα στο εύρος',
    };
  }
}

/// Ύπνος: τουλάχιστον 7 ώρες για ενήλικες 18–60 ετών (σύσταση AASM/SRS· Watson κ.ά., Sleep 2015).
/// Round 1 (S4-5): η σύσταση βγήκε σχεδόν μόνο από ώρες ύπνου που ΔΗΛΩΝΑΝ οι ίδιοι οι άνθρωποι· η συσκευή μετρά τον
/// ύπνο χωρίς τα ξυπνήματα. Σε 669 ενήλικες ο μετρημένος ύπνος ήταν 6,0 ώρες έναντι 6,8 δηλωμένων· όσοι κοιμούνταν
/// (μετρημένα) 7 ώρες δήλωναν 0,4 ώρες παραπάνω (Lauderdale κ.ά., Epidemiology 2008). Γι' αυτό μέσος όρος έως 30 λεπτά
/// κάτω από τις 7 ώρες λέγεται «κοντά στο κάτω όριο» ([RefRange.nearBelow]), και «κάτω από το εύρος» μόνο κάτω από 6
/// ώρες 30 λεπτά. Το όριο των 30 λεπτών είναι δική μας, συντηρητική επιλογή (μικρότερο από τη διαφορά της μελέτης).
const sleepNearBelowMin = 30.0;

RefRange? sleepRange(Profile p, DateTime today) {
  final age = p.ageOn(today);
  if (age != null && (age < 18 || age > 60)) return null;
  return const RefRange(
    low: 7 * 60,
    nearBelow: sleepNearBelowMin,
    text: 'τουλάχιστον 7 ώρες για ενήλικες',
    cite: 'AASM και Sleep Research Society (Watson κ.ά., Sleep 2015), ενήλικες 18–60 ετών. Η σύσταση βγήκε από ώρες ύπνου '
        'που δήλωναν οι ίδιοι οι άνθρωποι· οι συσκευές μετρούν συνήθως μισή με μία ώρα λιγότερο (Lauderdale κ.ά., '
        'Epidemiology 2008)',
  );
}

