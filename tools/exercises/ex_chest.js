const BREATH = 'Ανάσα σε κάθε επανάληψη: εκπνοή στην προσπάθεια, εισπνοή στην επιστροφή. Μην κρατάς καθόλου την αναπνοή· ανεβάζει απότομα την πίεση.';

// Πίεση με αλτήρες: χέρια από το ύψος του στήθους (p=1) ως πάνω από τους ώμους (p=0).
// up = κατεύθυνση της πίεσης (κάθετα στο πάτωμα).
// round1, U5-20: ο αγκώνας κινείται σε τόξο και ο πήχης μένει πάντα κάθετος (ο καρπός πάνω από τον αγκώνα), όπως λέει ο
// οδηγός «πήχεις κάθετοι». Πριν το χέρι πήγαινε σε ευθεία γραμμή και ο πήχης έγερνε ως 45°. Ο βραχίονας 45° από τον κορμό,
// από 77° πάνω ως 30° κάτω από τη γραμμή των ώμων (στο κάτω σημείο ο αγκώνας λίγο κάτω από τον πάγκο, όχι πιο βαθιά).
// [wide] μένει στην υπογραφή για τις κλήσεις· το άνοιγμα το ορίζει η γωνία των 45°.
const pressArms = (p, up, wide) => (J, F) => { // eslint-disable-line no-unused-vars
  const D = E.D;
  // Κάθετα στο «πάνω», ώστε ο βραχίονας να έχει πάντα το μήκος του (στον πάγκο σε κλίση το chest.y γέρνει).
  const side = s => ortho(add(mul(F.chest.x, s * Math.cos(45 * D)), mul(F.chest.y, -Math.sin(45 * D))), up);
  const t = (sh, s) => {
    const th = lerp(77, -30, p) * D;
    const elbow = add(sh, add(mul(up, A.uarm * Math.sin(th)), mul(side(s), A.uarm * Math.cos(th))));
    return add(elbow, mul(up, A.farm + A.grip));
  };
  return { armL: { to: t(J.shL, 1), pole: side(1) }, armR: { to: t(J.shR, -1), pole: side(-1) } };
};

