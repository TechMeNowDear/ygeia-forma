// Αλτήρας στο χέρι k: handle = 'lat' (λαβή κάθετα στο επίπεδο της κάμψης) ή 'ant' (σφυρί).
function dbAt(S, B, k, kind, plates) {
  const F = B.F['farm' + k];
  S.dumbbell(B.J['grp' + k], kind === 'ant' ? F.ant : F.lat, plates || [2.5]);
}

const standCurl = (hammer) => ({
  frame(S, p) {
    const el = 6 + 134 * p;
    const B = stand({ knee: 6, pitch: 2, w: 0.28, toe: 6,
      arms: () => ({ armL: { sf: 10 * p, sa: 7, el }, armR: { sf: 10 * p, sa: 7, el } }) ,
      loads: J => [[J.grpL, 6.8], [J.grpR, 6.8]] });
    S.body(B);
    dbAt(S, B, 'L', hammer ? 'ant' : 'lat'); dbAt(S, B, 'R', hammer ? 'ant' : 'lat');
    S.muscles(hammer ? ['brachio', 'biceps', 'forearm'] : ['biceps', 'forearm', 'brachio']);
  },
});

